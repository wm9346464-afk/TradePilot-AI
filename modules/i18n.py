def t(key: str, lang: str = "zh") -> str:
    """
    Get translated text by key and language.

    Args:
        key: Translation key (dot-separated, e.g. "home.title")
        lang: Language code ("zh" or "en")

    Returns:
        Translated text. Falls back to Chinese if key not found,
        then to the key itself if neither language has it.
    """
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["zh"])
    if key in lang_dict:
        return lang_dict[key]
    # Fallback to Chinese
    if key in TRANSLATIONS["zh"]:
        return TRANSLATIONS["zh"][key]
    # Last resort: return the key
    return key


def get_current_lang() -> str:
    """
    Get current language from Streamlit session state.
    Defaults to "zh" if not set.
    """
    try:
        import streamlit as st
        return st.session_state.get("lang", "zh")
    except Exception:
        return "zh"
